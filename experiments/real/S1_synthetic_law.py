"""
S1_synthetic_law.py — synthetic controls for the learned node (FR3 chain geometry).

S1a (do-no-harm): the data are generated by an EXACT serial-chain law (fixed
random base/tool + per-joint constant SE(3) corrections + pose noise).
Prediction: the relaxed node (X13/X14 placement) does not beat the exact dense
model; psi stays ~0. If it *does* beat, the X13 gain is capacity, not law
misspecification.

S1b (positive control): the data are generated with a KNOWN pair-dependent
deformation of the composition law (a fixed small function of the accumulated
pose A and the step B, evaluated at every joint). The exact node cannot represent
it (a training-independent floor); the relaxed node should recover the
deformation and beat the exact dense model.

Models: exact dense = E34.ScrewArm(mode='const'); relaxed = X13.LearnedNodeArm
(MLP psi, 396p) and X14.FourierLawArm (Fourier psi, 240p).
Protocol: X7-style splits, seeds, N=20..80, E34.train_recipe (4000 epochs,
cosine2, clip=0), position metric on held-out synthetic poses.

Registered predictions (plan 2026-09-29, before the run):
  P-S1a: relaxed ~ exact dense on the exact-law data (|diff| < 0.15 mm, paired);
  P-S1b: relaxed < exact dense on the deformed-law data (paired, N>=40);
  P-S1c (boundary): if S1a shows a relaxed win, the X13 interpretation (law
         misspecification) is refuted in favour of capacity.

Output: repro/json/S1_synthetic_law.<ts>.json via repro/dump.
Run:  python S1_synthetic_law.py [--quick]
"""

import argparse
import os
import sys
import time

import numpy as np
import torch
from scipy import stats

_HERE = os.path.dirname(os.path.abspath(__file__))
_REPO = os.path.dirname(os.path.dirname(_HERE))
if _HERE not in sys.path:
    sys.path.insert(0, _HERE)
if _REPO not in sys.path:
    sys.path.insert(0, _REPO)

import X7_robot_calibration as X7          # noqa: E402
import E34_x7_recipe as E34                 # noqa: E402
import X13_learned_node as X13              # noqa: E402
import X14_fourier_law as X14               # noqa: E402
import X7_gn_ls as GN                       # noqa: E402
from repro.dump import save_dump            # noqa: E402

DT = E34.DT
RESULTS = {}


def gen_dataset(C, E, n, seed, deform=False, noise_pos=0.0005, noise_rot=0.0017):
    """Exact serial-chain data, optionally with a fixed pair-dependent deformation
    exp(eta(A,B)) applied at every composition (eta linear in chart features)."""
    g = torch.Generator().manual_seed(seed)
    qs = (torch.rand(n, 7, generator=g, dtype=DT) - 0.5) * (2.0 * np.pi * 0.8)
    base_r = (torch.rand(3, generator=g, dtype=DT) - 0.5) * 0.02
    base_t = (torch.rand(3, generator=g, dtype=DT) - 0.5) * 0.02
    tool_r = (torch.rand(3, generator=g, dtype=DT) - 0.5) * 0.02
    tool_t = (torch.rand(3, generator=g, dtype=DT) - 0.5) * 0.02
    corr = (torch.rand(len(C), 6, generator=g, dtype=DT) - 0.5) * 0.02
    if deform:
        D = (torch.rand(6, 3, generator=g, dtype=DT) - 0.5) * 0.02
    Cin = [(X7.mat_to_quat(torch.tensor(C[i][:3, :3], dtype=DT)),
            torch.tensor(C[i][:3, 3], dtype=DT)) for i in range(len(C))]
    Ei = (X7.mat_to_quat(torch.tensor(E[:3, :3], dtype=DT)),
          torch.tensor(E[:3, 3], dtype=DT))
    z3 = torch.zeros(3, dtype=DT)
    poses = []
    for k in range(n):
        pose = (E34.quat_exp(base_r), base_t)
        for i in range(len(C)):
            qc, tc = E34.screw_exp(corr[i].unsqueeze(0))
            step = X7.compose(Cin[i], (qc[0], tc[0]))
            step = X7.compose(step, (X7.rotz_quat(qs[k, i].unsqueeze(0))[0], z3))
            if deform:
                thB = X14.chart_feats(step)[0]
                f = torch.cat([torch.ones_like(thB), thB, torch.sin(thB)],
                              -1).unsqueeze(0)
                eq, et = E34.screw_exp(f @ D.t())
                step = X7.compose(step, (eq[0], et[0]))
            pose = X7.compose(pose, step)
        pose = X7.compose(pose, Ei)
        pose = X7.compose(pose, (E34.quat_exp(tool_r), tool_t))
        poses.append(pose)
    oq = torch.stack([p[0] for p in poses])
    ot = torch.stack([p[1] for p in poses])
    rng = np.random.default_rng(seed)
    ot = ot + torch.tensor(rng.normal(0, noise_pos, ot.shape), dtype=DT)
    rv = torch.tensor(rng.normal(0, noise_rot, (n, 3)), dtype=DT)
    oq = X7.quat_mul(oq, E34.quat_exp(rv))
    return qs, oq, ot


def run_setting(tag, deform, C, E, sizes, seeds, epochs, models=('exact_dense', 'relaxed_fourier')):
    data = [gen_dataset(C, E, 500, 7000 + s, deform=deform) for s in range(seeds)]
    res = {(n, k): [] for n in sizes for k in models}
    for s in range(seeds):
        q, oq, ot = data[s]
        perm = np.random.default_rng(1000 + s).permutation(len(q))
        for n_tr in sizes:
            tr, te = perm[:n_tr], perm[n_tr:]
            q_tr, oq_tr, ot_tr = q[tr], oq[tr], ot[tr]
            q_te, oq_te, ot_te = q[te], oq[te], ot[te]
            line = []
            for k in models:
                if k == 'exact_dense':
                    m = E34.ScrewArm(C, E, mode='const')
                elif k == 'relaxed_mlp':
                    m = X13.LearnedNodeArm(C, E, edge_dense=True)
                else:
                    m = X14.FourierLawArm(C, E, edge_dense=True)
                m, _ = E34.train_recipe(m, q_tr, oq_tr, ot_tr, epochs, 5e-3, s,
                                        clip=0.0, ang_weight=1.0, warm_epochs=0,
                                        loss_form='cosine2')
                res[(n_tr, k)].append(GN.eval_pos(m, q_te, oq_te, ot_te))
                line.append(f'{k} {res[(n_tr, k)][-1][0]:.3f}')
            print(f'[{tag} seed {s} n={n_tr}] ' + ' | '.join(line), flush=True)
    for n_tr in sizes:
        for k in models:
            a = np.array([v[0] for v in res[(n_tr, k)]])
            RESULTS[f'S1:{tag}:n{n_tr}:{k}'] = dict(
                pos_mm_mean=float(a.mean()), pos_mm_std=float(a.std()),
                per_seed=[float(x) for x in a])
        a = np.array([v[0] for v in res[(n_tr, 'exact_dense')]])
        for k in models:
            if k == 'exact_dense':
                continue
            b = np.array([v[0] for v in res[(n_tr, k)]])
            if len(a) >= 2 and len(a) == len(b):
                t, p = stats.ttest_rel(b, a)
                RESULTS[f'S1:{tag}:paired:n{n_tr}:{k}_vs_exact'] = dict(
                    diff=float(b.mean() - a.mean()), t=float(t), p=float(p))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--sizes', default='20,80,160')
    ap.add_argument('--models', default='exact_dense,relaxed_fourier')
    ap.add_argument('--seeds', type=int, default=5)
    ap.add_argument('--epochs', type=int, default=4000)
    ap.add_argument('--quick', action='store_true')
    args = ap.parse_args()
    if args.quick:
        args.sizes, args.seeds, args.epochs = '20', 1, 300
    sizes = [int(s) for s in args.sizes.split(',')]
    t0 = time.time()
    C, E = X7.extract_nominal_chain()
    models = tuple(args.models.split(','))
    run_setting('exact', False, C, E, sizes, args.seeds, args.epochs, models)
    run_setting('deformed', True, C, E, sizes, args.seeds, args.epochs, models)
    RESULTS['S1:_meta_local'] = dict(wall_s=time.time() - t0, deform_dim=3,
                                     noise_pos_mm=0.5, noise_rot_deg=0.1)
    p = save_dump(RESULTS, __file__, quick=args.quick, args=args,
                  seeds=args.seeds, epochs=args.epochs)
    print('dump ->', p)


if __name__ == '__main__':
    main()

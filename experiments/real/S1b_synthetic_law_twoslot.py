"""
S1b_synthetic_law_twoslot.py — S1 synthetic controls under the FINAL two-slot head
(registered before run).

S1 showed that on synthetic data generated by an EXACT serial-chain law the
relaxation never wins (and overfits at small N), while on data deformed by a known
pair-dependent function it recovers the noise floor. Here the relaxed head is the
two-slot (global trend + local kernel), so the R-2 claim ("no gain where the data
obey the law") is checked on the final head.

Registered prediction (plan R-2): the two-slot reproduces S1 --- relaxed ~ exact on
the exact law (no held-out gain), relaxed < exact on the deformed law.

Output: repro/json/S1b_synthetic_law_twoslot.<ts>.json via repro/dump.
Run:  python S1b_synthetic_law_twoslot.py [--quick]
"""

import argparse
import os
import sys
import time

import numpy as np
import torch
from scipy import stats
from scipy.cluster.vq import kmeans2

_HERE = os.path.dirname(os.path.abspath(__file__))
_REPO = os.path.dirname(os.path.dirname(_HERE))
if _HERE not in sys.path:
    sys.path.insert(0, _HERE)
if _REPO not in sys.path:
    sys.path.insert(0, _REPO)

import S1_synthetic_law as S1               # noqa: E402
import X7_robot_calibration as X7           # noqa: E402
import E34_x7_recipe as E34                  # noqa: E402
import X14_fourier_law as X14                # noqa: E402
import X33_fr3_twoslot as X33                # noqa: E402
import X34_fr3_kernel as X34                 # noqa: E402
import X7_gn_ls as GN                        # noqa: E402
from repro.dump import save_dump             # noqa: E402

DT = torch.float64
RESULTS = {}


def make_2slot(C, E, q_tr, seed, centers=20):
    probe = X14.FourierLawArm(C, E, edge_dense=True)
    feats = X34.collect_feats(probe, q_tr)
    cen, _ = kmeans2(feats.numpy(), centers, minit='++', seed=seed)
    ctr = torch.tensor(cen, dtype=DT)
    dc = torch.cdist(ctr, ctr)
    bw = float(torch.median(dc[dc > 0]))
    m = X14.FourierLawArm(C, E, edge_dense=True)
    m.psi = X33.TwoSlotPsi(ctr, bw)
    return m


def run_setting(tag, deform, C, E, sizes, seeds, epochs):
    models = ('exact_dense', 'relaxed_fourier', 'relaxed_2slot')
    data = [S1.gen_dataset(C, E, 500, 7000 + s, deform=deform) for s in range(seeds)]
    res = {(n, k): [] for n in sizes for k in models}
    for s in range(seeds):
        q, oq, ot = data[s]
        perm = np.random.default_rng(1000 + s).permutation(len(q))
        for n_tr in sizes:
            tr, te = perm[:n_tr], perm[n_tr:]
            q_tr, oq_tr, ot_tr = q[tr], oq[tr], ot[tr]
            q_te, oq_te, ot_te = q[te], oq[te], ot[te]
            line = []
            for k in models:
                if k == 'exact_dense':
                    m = E34.ScrewArm(C, E, mode='const')
                elif k == 'relaxed_fourier':
                    m = X14.FourierLawArm(C, E, edge_dense=True)
                else:
                    m = make_2slot(C, E, q_tr, s)
                m, _ = E34.train_recipe(m, q_tr, oq_tr, ot_tr, epochs, 5e-3, s,
                                        clip=0.0, ang_weight=1.0, warm_epochs=0,
                                        loss_form='cosine2')
                res[(n_tr, k)].append(GN.eval_pos(m, q_te, oq_te, ot_te))
                line.append(f'{k} {res[(n_tr, k)][-1][0]:.3f}')
            print(f'[{tag} seed {s} n={n_tr}] ' + ' | '.join(line), flush=True)
    for n_tr in sizes:
        for k in models:
            a = np.array([v[0] for v in res[(n_tr, k)]])
            RESULTS[f'S1b:{tag}:n{n_tr}:{k}'] = dict(
                pos_mm_mean=float(a.mean()), pos_mm_std=float(a.std()),
                per_seed=[float(x) for x in a])
        a = np.array([v[0] for v in res[(n_tr, 'exact_dense')]])
        for k in models:
            if k == 'exact_dense':
                continue
            b = np.array([v[0] for v in res[(n_tr, k)]])
            if len(a) >= 2 and len(a) == len(b):
                t, p = stats.ttest_rel(b, a)
                RESULTS[f'S1b:{tag}:paired:n{n_tr}:{k}_vs_exact'] = dict(
                    diff=float(b.mean() - a.mean()), t=float(t), p=float(p))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--sizes', default='20,80,160')
    ap.add_argument('--seeds', type=int, default=5)
    ap.add_argument('--epochs', type=int, default=4000)
    ap.add_argument('--quick', action='store_true')
    args = ap.parse_args()
    if args.quick:
        args.sizes, args.seeds, args.epochs = '20', 1, 300
    sizes = [int(s) for s in args.sizes.split(',')]
    t0 = time.time()
    C, E = X7.extract_nominal_chain()
    run_setting('exact', False, C, E, sizes, args.seeds, args.epochs)
    run_setting('deformed', True, C, E, sizes, args.seeds, args.epochs)
    RESULTS['S1b:_meta_local'] = dict(wall_s=time.time() - t0)
    out = save_dump(RESULTS, __file__, quick=args.quick, args=args,
                    seeds=args.seeds, epochs=args.epochs)
    print('dump:', out)


if __name__ == '__main__':
    main()

def clean(s):
    s = s.strip()
    for a, b in [(r'\checkmark', '✓'), (r'\pverdict', '◐'), (r'\degunit', '°'),
                 (r'\pm', '±'), (r'\cdot', '·'), (r'\equiv', '≡'), (r'\arccos', 'arccos'),
                 (r'\arcsin', 'arcsin'), (r'\chi', 'χ'), (r'\mathbb{Z}', 'ℤ'),
                 (r'\cos', 'cos'), (r'\exp', 'exp'), (r'\omega', 'ω'),
                 (r'\propto', '∝'), (r'\psi', 'ψ'), (r'\sigma', 'σ'),
                 (r'\pi', 'π'), (r'\lambda', 'λ'), (r'\alpha', 'α'),
                 (r'\mu', 'μ'), (r'\theta', 'θ'), (r'\Delta', 'Δ'),
                 (r'\emph', ''), (r'\textbf', ''), (r'\mathrm', ''), (r'\S', '§'),
                 (r'\times', '×'), (r'\to', '→'), (r'\approx', '≈'), (r'\le', '≤'),
                 (r'\ge', '≥'), (r'\gg', '≫'), (r'\sim', '~'), (r'\qtilde', 'q̃'),
                 (r'\%', '%'), (r'\|', '|'), (r'\,', ' ')]:
        s = s.replace(a, b)
    # Common TeX grouping: {=}, {\pm}, {\to} etc.  The braces are not meaningful
    # in Markdown, so strip them after the operator macros have been substituted.
    s = s.replace('``', '“').replace("''", '”')
    s = s.replace('{', '').replace('}', '')
    s = s.replace('~', ' ').replace('$', '')
    s = re.sub(r'\\[a-zA-Z]+', '', s)
    s = s.replace('\\', ' ')
    s = re.sub(r'\s+', ' ', s).strip()
    return s.replace('--', '–')


def parse(tex):
    body = tex.split(r'\begin{document}')[1]
    tables = re.findall(r'\\begin\{longtable\}.*?\\end\{longtable\}', body, flags=re.S)
    rows = []
    skip = (r'\begin{longtable}', r'\end{longtable}', r'\toprule', r'\midrule',
            r'\bottomrule', r'\endfirsthead', r'\endhead', r'\endfoot',
            r'\caption', r'\label')
    for b in tables:
        lines = [ln for ln in b.split('\n') if not any(t in ln for t in skip)]
        for r in '\n'.join(lines).split('\\\\'):
            r = r.strip()
            if ' & ' not in r:
                continue
            cells = [c.strip() for c in r.split('&')]
            if len(cells) == 5 and re.match(r'^[PXL]', cells[0]) and 'Expt' not in cells[1]:
                rows.append([clean(c).replace('|', r'\|') for c in cells])
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('tex')
    ap.add_argument('out', nargs='?', default='docs/predictions.md')
    args = ap.parse_args()
    rows = parse(open(args.tex, encoding='utf-8').read())
    # The paper's final X6b statement is deterministic agreement, not a TOST claim;
    # keep the pre-specified check but do not present it as a statistical-equivalence pass.
    for c in rows:
        if c[0] == 'P-X6b':
            c[3] = 'differences ≤0.0013°; deterministic agreement (paper reports no TOST)'
        if c[0] == 'P-POOL':
            c[3] = 'historical primary: Fisher χ²=58.3, p≈7·10^-12; final POOL2 primary = 58.5'
        if c[0] == 'P-POOL-EXT':
            c[3] = 'historical pre-final global head: gate fails (p=0.26); final kernel gate passes — see P-POOL-2'
    for c in rows:
        if c[1] in SCRIPT:
            c[1] = f'[{c[1]}](../{SCRIPT[c[1]]})'
    md = [LEGEND.rstrip('\n')]
    for c in rows:
        md.append('| ' + ' | '.join(c) + ' |')
    with open(args.out, 'w', encoding='utf-8') as f:
        f.write('\n'.join(md) + '\n')
    print(f'wrote {args.out}: {len(rows)} rows')


if __name__ == '__main__':
    sys.exit(main())
